from .common import circle, arc
H = lambda y, x0=0, x1=1: [(x0, y), (x1, y)]
V = lambda x, y0=1, y1=0: [(x, y0), (x, y1)]
D = lambda a, b: [a, b]
def bowl(top, bot, x1=.55, rx=.45):
    """a D-shaped bowl from the stem: out along `top`, round to `bot`, back."""
    ym = (top + bot) / 2
    return [(0, top), (x1, top)] + arc(x1, ym, rx, (top - bot) / 2, 90, -90)[1:] + [(0, bot)]
