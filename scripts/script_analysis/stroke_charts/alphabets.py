"""Stroke guesses for Latin, Greek (lower case) and Cyrillic, drawn on DejaVu Sans outlines.
Order follows a hand: connected strokes in sequence, then left-to-right and top-to-bottom as the tie-breaker."""
from .common import circle, arc
H = lambda y, x0=0, x1=1: [(x0, y), (x1, y)]
V = lambda x, y0=1, y1=0: [(x, y0), (x, y1)]
D = lambda a, b: [a, b]
mx = lambda s: [(1 - x, y) for x, y in s]
def P(*parts):
    out = []
    for p in parts:
        out += list(p)[1:] if out else list(p)
    return out
def bowl(top, bot, x1=.55, rx=.45):
    ym = (top + bot) / 2
    return P([(0, top), (x1, top)], arc(x1, ym, rx, (top - bot) / 2, 90, -90), [(0, bot)])
E_ = lambda cy, ry: arc(.5, cy, .5, ry, 0, 330)

